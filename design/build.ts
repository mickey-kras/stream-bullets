// Builds components/bundle.css, components/bundle.js and the kit.js of each UI kit: node design/build.ts
// See the Build section of design/README.md.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build, type BuildOptions, type Plugin } from "esbuild";
import { compile } from "tailwindcss";
import { buildSite } from "./site.ts";

const design: string = fileURLToPath(new URL("./", import.meta.url));
const app: string = resolve(design, "..");
const root: string = `${design}components/`;
const namespace = "StreamBulletsDesignSystem_e1d9fa";

// bundle.css is the CSS of the app: app/styles.css as Tailwind compiles it (preflight only, no utilities),
// the self-hosted fonts, and the style sheets that the landing and overlay routes import.
const routeStyles: string[] = [
  "app/components/station/landing.css",
  "app/components/overlay/composition.css",
  "app/components/overlay/wasteland/wasteland.css",
];
const compiler = await compile(await readFile(`${app}/app/styles.css`, "utf8"), {
  base: `${app}/app`,
  loadStylesheet: async (id: string, base: string) => {
    const path: string = id === "tailwindcss" ? `${app}/node_modules/tailwindcss/index.css` : resolve(base, id);
    return { path, base: dirname(path), content: await readFile(path, "utf8") };
  },
});
const sheets: string[] = [
  await readFile(`${app}/public/fonts.css`, "utf8"),
  compiler.build([]),
  ...(await Promise.all(routeStyles.map((path: string) => readFile(`${app}/${path}`, "utf8")))),
];
// In Claude, each file under assets/ is an upload at /_blob/<id> (design-system.json lists the ids).
// --claude builds for Claude. Without it, the build points at the files in design/.
const claude: boolean = process.argv.includes("--claude");
const groups: Record<string, { files: Record<string, { name: string; blob: string }> }> = JSON.parse(
  await readFile(`${design}design-system.json`, "utf8"),
).assetGroups;
const uploads = new Map<string, string>();
for (const [group, entry] of Object.entries(groups))
  for (const file of Object.values(entry.files)) uploads.set(`assets/${group}/${file.name}`, file.blob);

// The app serves its files from public/. The design system has a copy of each one: find it by file name.
const copies = new Map<string, string>();
for (const folder of ["fonts", "assets"]) {
  for (const entry of await readdir(`${design}${folder}`, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const path = `${dirname(`${entry.parentPath}/${entry.name}`).slice(design.length)}/${entry.name}`;
    copies.set(entry.name, path);
  }
}
const target = (path: string): string => {
  if (!claude || !path.startsWith("assets/")) return `../${path}`;
  const blob: string | undefined = uploads.get(path);
  if (!blob) throw new Error(`No upload id in design-system.json for ${path}`);
  return `/_blob/${blob}`;
};
const css: string = sheets
  .join("\n")
  .replace(/url\((["']?)((?!data:|#|%23)[^"')]+)\1\)/g, (_match: string, _quote: string, url: string) => {
    const copy: string | undefined = copies.get(basename(url));
    if (!copy) throw new Error(`No copy in design/ of the file that the app CSS loads: ${url}`);
    return `url("${target(copy)}")`;
  });
// The Claude design system shows each theme with data-theme="<id>" on <html>, and its preview frames are
// small documents. For Claude, each theme selector of the app also matches its data-theme, and the page
// may scroll as the site previews do (site.ts).
const claudeThemes: [RegExp, string][] = [
  [/\[data-contrast="?high"?\]/g, ":is([data-contrast=high],[data-theme=high-contrast])"],
  [/\[data-cvd="?pd"?\]/g, ":is([data-cvd=pd],[data-theme=protan-deutan])"],
  [/\[data-cvd="?tri"?\]/g, ":is([data-cvd=tri],[data-theme=tritan])"],
];
const claudeCss = (text: string): string =>
  `${claudeThemes.reduce((out: string, [from, to]: [RegExp, string]) => out.replace(from, to), text)}
html,body{height:auto;min-height:100%;overflow:auto;display:block}`;
await writeFile(
  `${root}bundle.css`,
  `/* Generated by design/build.ts from the CSS of the app. Do not edit. */\n${claude ? claudeCss(css) : css}`,
);

const pageModules: Record<string, string> = {
  react: "module.exports = window.React;",
  "react-dom": "module.exports = window.ReactDOM;",
  "react-dom/client": "module.exports = window.ReactDOM;",
  // The React 18 UMD build has no JSX runtime. The sources and Radix compile to calls of this one.
  "react/jsx-runtime": [
    "const React = window.React;",
    "export const Fragment = React.Fragment;",
    "export const jsx = (type, props, key) => React.createElement(type, key === undefined ? props : { ...props, key });",
    "export const jsxs = jsx;",
  ].join("\n"),
};

// Resolves the listed imports to globals of the page instead of bundling them.
function pageGlobals(modules: Record<string, string>): Plugin {
  const filter = new RegExp(
    `^(${Object.keys(modules)
      .map((name: string) => name.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&"))
      .join("|")})$`,
  );
  return {
    name: "page-globals",
    setup(builder) {
      builder.onResolve({ filter }, (args) => ({ path: args.path, namespace: "page-global" }));
      builder.onLoad({ filter: /.*/, namespace: "page-global" }, (args) => ({
        contents: modules[args.path],
        loader: "js",
      }));
    },
  };
}

const common: BuildOptions = {
  // The Claude build gives assetUrl() in src/core/assets.js the upload address of each image.
  define: claude
    ? {
        "globalThis.__DS_UPLOADS__": JSON.stringify(
          Object.fromEntries(
            [...uploads].map(([path, blob]: [string, string]) => [path.slice("assets/".length), `/_blob/${blob}`]),
          ),
        ),
      }
    : {},
  bundle: true,
  format: "iife",
  target: "es2020",
  charset: "utf8",
  jsx: "automatic",
  logLevel: "warning",
};

// The manifest line lists one part for each module of src/index.js, as the Claude design system expects.
const index: string = await readFile(`${root}src/index.js`, "utf8");
const components: { name: string }[] = [...index.matchAll(/from "\.\/\w+\/(\w+)\.jsx"/g)].map(
  (match: RegExpExecArray) => ({ name: match[1] }),
);

await build({
  ...common,
  entryPoints: [`${root}src/index.js`],
  outfile: `${root}bundle.js`,
  globalName: namespace,
  banner: { js: `/* @ds-bundle: ${JSON.stringify({ format: 4, namespace, components })} */` },
  plugins: [pageGlobals(pageModules)],
});

for (const kit of ["WebsiteKit", "ObsOverlayKit"]) {
  await build({
    ...common,
    entryPoints: [`${root}${kit}/main.jsx`],
    outfile: `${root}${kit}/kit.js`,
    plugins: [pageGlobals({ ...pageModules, "../src/index.js": `module.exports = window.${namespace};` })],
  });
}

// Outside Claude, an upload URL in the parts or kits goes to its file. The pages that load them
// (components/<Name>/preview.html and site/previews/<Name>.html) are two folders below design/.
if (!claude) {
  const files = new Map<string, string>([...uploads].map(([path, blob]: [string, string]) => [blob, path]));
  for (const file of [`${root}bundle.js`, `${root}WebsiteKit/kit.js`, `${root}ObsOverlayKit/kit.js`]) {
    const code: string = await readFile(file, "utf8");
    await writeFile(
      file,
      code.replace(/\/_blob\/([0-9a-f]{32})/g, (_match: string, blob: string) => {
        const path: string | undefined = files.get(blob);
        if (!path) throw new Error(`No file in design-system.json for the upload ${blob} in ${basename(file)}`);
        return `../../${path}`;
      }),
    );
  }
  await buildSite(design);
}
