/**
 * Writes THIRD_PARTY_NOTICES.md: the name, version, license and license text of every package the app ships, which
 * is the runtime `dependencies` of package.json and their own runtime dependencies. Build tools (devDependencies)
 * do not ship and are not listed. `--check` fails when the file is out of date, so a dependency change cannot merge
 * without its notices, and the diff shows the reviewer which licenses changed (SECURITY.md, Dependency licenses).
 *
 *   node scripts/third-party-notices.ts          # rewrite the file
 *   node scripts/third-party-notices.ts --check  # CI
 */
import { readFile, readdir, realpath, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

interface Manifest {
  name: string;
  version: string;
  license?: string;
  dependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
}

interface Package {
  manifest: Manifest;
  text: string | null;
}

const root: string = join(dirname(new URL(import.meta.url).pathname), "..");
const output: string = join(root, "THIRD_PARTY_NOTICES.md");

/** The directory of `name` as `from` resolves it: pnpm puts a package's dependencies next to it. */
async function resolvePackage(from: string, name: string): Promise<string | null> {
  const modules: string = from.slice(0, from.lastIndexOf("/node_modules/") + "/node_modules".length);
  for (const base of from === root ? [join(root, "node_modules")] : [modules, join(root, "node_modules")]) {
    try {
      return await realpath(join(base, name));
    } catch {
      // Not installed here (an optional dependency for another platform): try the next place.
    }
  }
  return null;
}

async function licenseText(directory: string): Promise<string | null> {
  const files: string[] = (await readdir(directory)).filter((file: string): boolean =>
    /^(licen[cs]e|copying|notice)(\.|$)/i.test(file),
  );
  if (files.length === 0) return null;
  const texts: string[] = await Promise.all(
    files.sort().map(async (file: string): Promise<string> => (await readFile(join(directory, file), "utf8")).trim()),
  );
  return texts.join("\n\n");
}

async function shippedPackages(): Promise<Package[]> {
  const found = new Map<string, Package>();
  const visit = async (directory: string, optional: boolean): Promise<void> => {
    const manifest: Manifest = JSON.parse(await readFile(join(directory, "package.json"), "utf8")) as Manifest;
    const key = `${manifest.name}@${manifest.version}`;
    if (directory !== root) {
      if (found.has(key)) return;
      found.set(key, { manifest, text: await licenseText(directory) });
    }
    const required: string[] = Object.keys(manifest.dependencies ?? {});
    const extra: string[] = Object.keys(manifest.optionalDependencies ?? {});
    for (const name of [...required, ...extra]) {
      const child: string | null = await resolvePackage(directory, name);
      if (child) await visit(child, optional || extra.includes(name));
      else if (!optional && !extra.includes(name)) throw new Error(`${name} (needed by ${key}) is not installed.`);
    }
  };
  await visit(root, false);
  return [...found.values()].sort((a: Package, b: Package): number =>
    `${a.manifest.name}@${a.manifest.version}`.localeCompare(`${b.manifest.name}@${b.manifest.version}`),
  );
}

export function notices(packages: readonly Package[]): string {
  const lines: string[] = [
    "# Third-party notices",
    "",
    "StreamBullets ships the following open-source packages. Generated by `node scripts/third-party-notices.ts`; do not edit by hand.",
    "",
    "The fonts, icons and 3D library files in `public/assets` carry their own license files next to them.",
    "",
  ];
  for (const { manifest, text } of packages) {
    lines.push(`## ${manifest.name} ${manifest.version}`, "", `License: ${manifest.license ?? "not stated"}`, "");
    lines.push(text ? ["```text", text, "```"].join("\n") : "No license file in the package.", "");
  }
  return lines.join("\n");
}

const expected: string = notices(await shippedPackages());
if (process.argv.includes("--check")) {
  const current: string = await readFile(output, "utf8").catch((): string => "");
  if (current !== expected) {
    console.error("THIRD_PARTY_NOTICES.md is out of date. Run `node scripts/third-party-notices.ts` and review the diff.");
    process.exitCode = 1;
  }
} else {
  await writeFile(output, expected);
}
